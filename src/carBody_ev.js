// 차체 모양: buildEV (볼트 EV). 변신 부품·바퀴 등 공통 부분은 carModel.js
// 2026-11-10 디테일 작업: 매끈한 조약돌 몸통 + 앞 펜더, 덮인 뒷바퀴(빛나는 에어로 덮개), 긴 유리 캐노피(좌석·화면·요크 핸들),
//   앞뒤 라이트 바 + 세로 주간등, 빛나는 지붕 등뼈·충전구·바닥 줄, 카메라 미러, 디퓨저 핀, 빛나는 기둥 위 칼날 날개
import * as THREE from 'three';
import { R, arches, doorNumber, glowMat, loft, makeHelmet, rodGeometry } from './carModel.js';
import { bx, at, merge, kit, kf, pod, hoop, foil, softGlass, sidePlate, seatGeos } from './carBody_hyper.js';

export function buildEV({ add, body, M, look }) {
  const { paint, accent, trim, carbon, dark, metal, lamp, tailMat } = M;
  const neon = glowMat(look.accent, 1.7);
  const glass = softGlass('#3f6876', 0.72, 0.6);
  const W = [
    [-0.88, 1.65, true, 0.36, 0.3, 0.4],
    [0.88, 1.65, true, 0.36, 0.3, 0.4],
    [-0.9, -1.55, false, 0.37, 0.34, 0.4],
    [0.9, -1.55, false, 0.37, 0.34, 0.4],
  ];
  const K = kit(add, body);
  // --- 조약돌 몸통 (한 덩어리)
  add(loft([
    R(2.88, 0.46, 0.22, 0.4, 3), R(2.55, 0.74, 0.18, 0.53, 3.5), R(1.65, 0.8, 0.17, 0.62, 4), R(0.6, 0.96, 0.18, 0.66, 4),
    R(-0.8, 0.97, 0.2, 0.69, 4), R(-1.9, 0.86, 0.22, 0.68, 4), R(-2.55, 0.66, 0.28, 0.58, 3.5), R(-2.78, 0.44, 0.36, 0.5, 3),
  ], 22), paint, 0, 0, 0);
  // --- 앞 펜더(바퀴 위로 부드럽게 솟음) + 뒷바퀴를 통째로 덮는 덮개
  const fF = (s) => kf([
    [2.8, 0.14, 0.38, s * 0.62, 0.2, 3], [2.4, 0.3, 0.62, s * 0.68, 0.2, 3.5], [2.03, 0.33, 0.77, s * 0.7, 0.2, 4],
    [1.65, 0.33, 0.83, s * 0.7, 0.2, 4], [1.2, 0.32, 0.78, s * 0.7, 0.2, 4], [0.75, 0.26, 0.64, s * 0.7, 0.2, 3.5], [0.35, 0.2, 0.5, s * 0.72, 0.2, 3],
  ]);
  for (const s of [-1, 1]) {
    add(pod(1.65, 0.36, fF(s), 2.8, 0.35, { seg: 14 }), paint, 0, 0, 0);
    add(loft([
      R(-0.75, 0.16, 0.26, 0.6, 3.5, s * 0.8), R(-1.1, 0.32, 0.17, 0.8, 4.5, s * 0.775), R(-1.55, 0.33, 0.16, 0.84, 4.5, s * 0.775),
      R(-2.05, 0.31, 0.17, 0.78, 4.5, s * 0.765), R(-2.5, 0.22, 0.26, 0.6, 3.5, s * 0.7), R(-2.74, 0.1, 0.34, 0.5, 3, s * 0.56),
    ], 14), paint, 0, 0, 0);
    // 뒷바퀴 에어로 덮개: 검은 원판 + 빛나는 고리 + 바람개비 살
    K.put(carbon, at(new THREE.CylinderGeometry(0.33, 0.33, 0.016, 24).rotateZ(Math.PI / 2), s * 1.103, 0.4, -1.55));
    K.put(neon, at(new THREE.TorusGeometry(0.335, 0.012, 4, 20).rotateY(Math.PI / 2), s * 1.108, 0.4, -1.55), at(new THREE.TorusGeometry(0.1, 0.01, 4, 16).rotateY(Math.PI / 2), s * 1.112, 0.4, -1.55));
    for (let i = 0; i < 5; i++) K.put(paint, bx(0.012, 0.2, 0.05, 0, 0.21, 0, 0.5).rotateX((i * Math.PI * 2) / 5).translate(s * 1.112, 0.4, -1.55));
    // 앞바퀴 아치 테두리 빛 (아치 위쪽을 따라)
    K.put(neon, at(new THREE.TorusGeometry(0.425, 0.01, 4, 20, Math.PI * 0.8).rotateZ(Math.PI * 0.1).rotateY(-Math.PI / 2), s * 1.035, 0.36, 1.65));
  }
  arches(add, M, W.slice(0, 2), 0.03, 0.07, 0.08);
  // --- 긴 물방울 캐노피 (유리 한 장) + 틀 + 지붕 태양 전지판·빛나는 등뼈·센서
  const cs = [R(1.55, 0.3, 0.6, 0.64, 3), R(0.9, 0.6, 0.62, 1.0, 3), R(0, 0.66, 0.64, 1.15, 3), R(-1.0, 0.6, 0.66, 1.08, 3), R(-2.0, 0.4, 0.64, 0.86, 3), R(-2.5, 0.2, 0.6, 0.7, 3)];
  add(loft(cs, 20), glass, 0, 0, 0).castShadow = false;
  K.put(paint, hoop(cs[1], 0.026, 0, Math.PI, 9), hoop(cs[3], 0.028, 0, Math.PI, 9));
  K.put(carbon, hoop(R(-0.5, 0.64, 0.65, 1.13, 3), 0.014, 0, Math.PI, 9));
  K.put(dark, bx(0.5, 0.012, 0.9, 0, 1.146, -0.45, -0.045));
  for (let i = 0; i < 4; i++) K.put(metal, bx(0.5, 0.014, 0.012, 0, 1.158 - i * 0.012, -0.12 - i * 0.22, -0.045));
  K.put(neon, bx(0.03, 0.014, 1.5, 0, 1.066, -1.45, -0.15), bx(0.03, 0.014, 0.5, 0, 1.115, 0.42, 0.2));
  K.put(carbon, at(new THREE.CylinderGeometry(0.07, 0.09, 0.05, 12), 0, 1.165, 0.12));
  K.put(neon, at(new THREE.TorusGeometry(0.075, 0.008, 4, 14).rotateX(Math.PI / 2), 0, 1.185, 0.12));
  // 실내: 좌석 2개(밝은 색 줄), 떠 있는 화면, 요크 핸들, 가운데 빛나는 줄
  K.put(carbon, ...seatGeos(0, 0.46, -0.28), ...seatGeos(-0.36, 0.44, -0.75, 0.9), ...seatGeos(0.36, 0.44, -0.75, 0.9));
  K.put(accent, bx(0.1, 0.42, 0.02, 0, 0.74, -0.36, -0.25));
  K.put(dark, bx(1.1, 0.03, 2.4, 0, 0.64, -0.5), bx(1.0, 0.08, 0.3, 0, 0.68, 0.7, 0.2));
  K.put(neon, bx(0.6, 0.12, 0.015, 0, 0.8, 0.52, -0.3), bx(0.02, 0.012, 1.6, 0.18, 0.66, -0.4), bx(0.02, 0.012, 1.6, -0.18, 0.66, -0.4));
  K.put(carbon, bx(0.26, 0.03, 0.03, 0, 0.8, 0.34), bx(0.03, 0.09, 0.03, 0.13, 0.83, 0.34), bx(0.03, 0.09, 0.03, -0.13, 0.83, 0.34), bx(0.03, 0.03, 0.2, 0, 0.77, 0.44, 0.3));

  for (const s of [-1, 1]) {
    // 바닥 빛나는 줄 + 검은 치마 + 문 선·납작 손잡이
    K.put(carbon, bx(0.14, 0.05, 2.3, s * 0.94, 0.2, 0.0));
    K.put(neon, bx(0.02, 0.02, 2.3, s * 1.012, 0.225, 0.0), bx(0.012, 0.012, 1.3, s * 0.976, 0.6, -0.1, 0.03));
    K.put(dark, bx(0.012, 0.34, 0.012, s * 0.972, 0.47, 0.42), bx(0.012, 0.34, 0.012, s * 0.975, 0.47, -0.72));
    K.put(metal, bx(0.012, 0.02, 0.16, s * 0.978, 0.54, -0.5));
    // 카메라 미러 (가는 기둥 + 작은 눈)
    K.put(carbon, rodGeometry(new THREE.Vector3(s * 0.64, 0.74, 0.98), new THREE.Vector3(s * 0.9, 0.84, 0.92), 0.014));
    K.put(paint, loft([R(0.99, 0.035, 0.81, 0.88, 3, s * 0.92), R(0.84, 0.03, 0.82, 0.87, 3, s * 0.92)], 8));
    K.put(neon, bx(0.02, 0.02, 0.012, s * 0.92, 0.845, 0.995));
    // 앞: 세로 송곳니 주간등 + 격자 LED 4알 + 옆 공기 커튼
    K.put(neon, bx(0.035, 0.24, 0.04, s * 0.8, 0.37, 2.56, 0.3, s * 0.5));
    K.put(dark, bx(0.34, 0.02, 0.2, s * 0.62, 0.535, 2.52, 0.6, s * 0.3), bx(0.12, 0.14, 0.03, s * 0.64, 0.3, 2.74, 0, s * 0.45));
    for (let i = 0; i < 4; i++) K.put(lamp, bx(0.06, 0.045, 0.08, s * (0.5 + i * 0.08), 0.56, 2.55 - i * 0.022, 0.6));
    // 뒤: 세로 빛 기둥 + 반사판
    K.put(tailMat, bx(0.03, 0.2, 0.03, s * 0.6, 0.44, -2.72, 0, s * -0.4));
    K.put(neon, bx(0.012, 0.2, 0.03, s * 0.635, 0.44, -2.705, 0, s * -0.4));
  }
  // 충전구 (오른쪽 앞 펜더 뒤, 빛나는 고리)
  K.put(dark, at(new THREE.CylinderGeometry(0.055, 0.055, 0.012, 14).rotateZ(Math.PI / 2), 0.975, 0.52, 0.7));
  K.put(neon, at(new THREE.TorusGeometry(0.06, 0.008, 4, 16).rotateY(Math.PI / 2), 0.98, 0.52, 0.7));
  // 앞 라이트 바 (끝에서 끝까지) + 아래 얇은 공기 틈 + 보닛 선
  K.put(neon, bx(1.3, 0.022, 0.04, 0, 0.455, 2.72), bx(0.22, 0.03, 0.02, 0, 0.36, 2.875));
  K.put(dark, bx(0.9, 0.05, 0.03, 0, 0.27, 2.78), bx(0.012, 0.012, 1.3, 0.3, 0.58, 2.0, 0.12), bx(0.012, 0.012, 1.3, -0.3, 0.58, 2.0, 0.12));
  // 뒤 라이트 바 + 디퓨저 + 핀 5개 + 가운데 빛
  K.put(tailMat, bx(1.24, 0.03, 0.04, 0, 0.53, -2.77));
  K.put(neon, bx(1.3, 0.012, 0.045, 0, 0.565, -2.765));
  K.put(dark, bx(0.9, 0.1, 0.03, 0, 0.4, -2.79));
  K.put(carbon, bx(1.5, 0.03, 0.55, 0, 0.23, -2.45, 0.38));
  for (const x of [-0.6, -0.3, 0, 0.3, 0.6]) K.put(carbon, sidePlate([[-2.2, 0.13], [-2.76, 0.13], [-2.76, 0.36], [-2.3, 0.2]], 0.02, x));
  for (const x of [-0.45, -0.15, 0.15, 0.45]) K.put(neon, bx(0.02, 0.012, 0.3, x, 0.3, -2.62, 0.38));
  doorNumber(add, M, 0.985, 0.42, -0.12, 0.26);
  K.flush();

  // --- 앞 스플리터 (얇은 칼날 + 빛나는 앞 줄 + 끝 날개)
  const fWing = new THREE.Group();
  body.add(fWing);
  const KF = kit(add, fWing);
  KF.put(carbon, bx(1.8, 0.022, 0.34, 0, 0.15, 2.72));
  KF.put(neon, bx(1.8, 0.01, 0.025, 0, 0.158, 2.89));
  for (const s of [-1, 1]) KF.put(carbon, sidePlate([[2.9, 0.14], [2.56, 0.14], [2.56, 0.26], [2.82, 0.19]], 0.02, s * 0.9));
  KF.flush();
  // --- 떠 있는 칼날 뒷날개 (빛나는 기둥 2개, 끝이 아래로 굽음)
  const spoiler = new THREE.Group();
  body.add(spoiler);
  const KS = kit(add, spoiler);
  KS.put(paint, at(foil(0.9, 0.32, 0.04, 0.06), 0, 0.98, -2.42));
  for (const s of [-1, 1]) {
    KS.put(neon, bx(0.025, 0.36, 0.07, s * 0.46, 0.81, -2.38, 0.12));
    KS.put(carbon, bx(0.04, 0.36, 0.1, s * 0.46, 0.81, -2.4, 0.12));
    KS.put(trim, sidePlate([[-2.26, 0.98], [-2.6, 1.02], [-2.6, 0.84], [-2.3, 0.88]], 0.025, s * 0.9));
  }
  KS.flush();
  const drs = add(merge([foil(0.88, 0.15, 0.025, 0.05)]), accent, 0, 1.025, -2.57, spoiler);
  drs.rotation.x = 0.3;
  const helmet = makeHelmet(add, body, M);
  helmet.position.set(0, 0.92, -0.2);
  return {
    helmet, fWing, spoiler, drs,
    A: {
      wheels: W,
      tuck: { f: [0.8, 0.5], r: [0.84, 0.56] },
      helmet: [0, 0.92, -0.2],
      visor: [1.08, -0.7],
      armor: { y: 0.66, x: 0.94 },
      ram: { y: 0.08, z: 1.85 },
      spines: [[-0.7, 1.12], [-1.1, 1.08], [-1.5, 1.0], [-1.9, 0.9]],
      booster: { x: 0.45, y0: 0.5, y1: 0.92, z0: -0.6, dz: -1.25 },
      lift: { y: 0.66, z: -2.35, h: 0.25 },
      stab: [0.9, 0.98, -2.44],
      tailFin: [0, 1.12, -0.9],
      wing: [0.94, 0.48, 0.0],
      nitro: { x: 0.3, y: 0.36, z: -2.62, dz: -0.42 },
      vents: [[0.6, 0.63, 1.55], [0.6, 0.645, 1.3], [0.6, 0.655, 1.05]],
      glow: { y: 0.6, z: 1.95, len: 1.2, rot: 0.12, w: 0.06 },
      flames: [[0, 0.42, 0.6, -2.85]],
      motor: [0.38, 0.36, -2.75],
      spark: [0.9, 0.25, -2.05],
      seams: [0.98, 0.18, -0.1],
      lean: 0.04,
      drsRest: 0.3,
    },
  };
}
