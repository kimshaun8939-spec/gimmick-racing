// 차체 모양: buildWedge (레이저 웨지). 변신 부품·바퀴 등 공통 부분은 carModel.js
// 2026-11-10 디테일 작업: 종이접기처럼 면이 각진 쐐기. 각진 펜더, 유리 캐빈(좌석·핸들), 옆 흡입구 살(스트레이크),
//   코끝 LED 줄, 보닛 공기구멍, 뒤 창 루버, 육각 후미등, 네모 배기구 4개, 디퓨저 핀, 큰 각진 뒷날개
import * as THREE from 'three';
import { R, arches, doorNumber, glowMat, loft, makeHelmet } from './carModel.js';
import { bx, at, merge, facet, kit, kf, pod, hoop, softGlass, sidePlate, seatGeos } from './carBody_hyper.js';

export function buildWedge({ add, body, M, look }) {
  const { paint, accent, trim, carbon, dark, metal, lamp, tailMat } = M;
  const neon = glowMat(look.trim, 1.5);
  const glass = softGlass('#3a4f66', 0.74, 0.6);
  const W = [
    [-0.88, 1.5, true, 0.33, 0.3, 0.42],
    [0.88, 1.5, true, 0.33, 0.3, 0.42],
    [-0.92, -1.42, false, 0.39, 0.42, 0.45],
    [0.92, -1.42, false, 0.39, 0.42, 0.45],
  ];
  const K = kit(add, body);
  // --- 쐐기 몸통: 코는 종이처럼 얇고 뒤로 갈수록 두꺼워짐 (면이 각져 보이게)
  add(facet(loft([
    R(2.72, 0.62, 0.2, 0.27, 8), R(2.3, 0.84, 0.19, 0.39, 8), R(1.0, 0.9, 0.19, 0.57, 8), R(-0.4, 0.95, 0.19, 0.69, 8),
    R(-1.9, 0.95, 0.21, 0.8, 8), R(-2.38, 0.9, 0.3, 0.8, 8),
  ], 12)), paint, 0, 0, 0);
  // --- 각진 펜더 (네모난 덩어리가 바퀴를 덮음)
  const fF = (s) => kf([[2.4, 0.18, 0.34, s * 0.76, 0.2, 8], [1.95, 0.3, 0.6, s * 0.74, 0.2, 8], [1.5, 0.31, 0.74, s * 0.73, 0.2, 8], [1.05, 0.3, 0.7, s * 0.73, 0.2, 8], [0.6, 0.22, 0.56, s * 0.74, 0.2, 8]]);
  const fR = (s) => kf([[-0.5, 0.2, 0.62, s * 0.82, 0.32, 8], [-0.92, 0.37, 0.86, s * 0.77, 0.22, 8], [-1.42, 0.38, 0.92, s * 0.77, 0.22, 8], [-2.0, 0.37, 0.9, s * 0.76, 0.22, 8], [-2.4, 0.33, 0.83, s * 0.74, 0.3, 8]]);
  for (const s of [-1, 1]) {
    add(facet(pod(1.5, 0.33, fF(s), 2.4, 0.6, { seg: 12, arc: 6, nF: 3, nR: 3 })), paint, 0, 0, 0);
    add(facet(pod(-1.42, 0.39, fR(s), -0.5, -2.4, { seg: 12, arc: 6, nF: 3, nR: 3 })), paint, 0, 0, 0);
  }
  arches(add, M, W, 0.03, 0.07, 0.1, carbon);
  // --- 유리 캐빈: 앞유리가 보닛과 거의 한 줄로 이어짐 + 검은 틀 + 지붕
  const cs = [R(1.3, 0.58, 0.5, 0.55, 6), R(0.35, 0.68, 0.6, 1.02, 6), R(-0.45, 0.68, 0.66, 1.07, 6), R(-1.1, 0.66, 0.72, 0.99, 6)];
  add(facet(loft(cs, 12)), glass, 0, 0, 0).castShadow = false;
  add(facet(loft([R(0.32, 0.56, 0.995, 1.05, 6), R(-0.45, 0.6, 1.035, 1.095, 6), R(-1.1, 0.58, 0.955, 1.01, 6)], 12)), paint, 0, 0, 0);
  K.put(carbon, hoop(cs[1], 0.024, 0, Math.PI, 10), hoop(cs[2], 0.024, 0, Math.PI, 10), hoop(cs[3], 0.026, 0, Math.PI, 10));
  for (const s of [-1, 1]) K.put(carbon, bx(0.03, 0.03, 1.06, s * 0.6, 0.79, 0.84, 0.47, s * 0.09)); // 앞유리 옆 기둥
  K.put(dark, bx(0.5, 0.02, 0.012, 0.2, 0.62, 1.12, 0.47), bx(0.012, 0.02, 0.5, 0.3, 0.72, 0.9, 0.47)); // 와이퍼
  // 실내: 좌석 2개, 계기판, 핸들 (운전자는 왼쪽)
  K.put(carbon, ...seatGeos(0.3, 0.4, -0.35), ...seatGeos(-0.3, 0.4, -0.35));
  K.put(trim, bx(0.1, 0.4, 0.02, 0.3, 0.68, -0.43, -0.25), bx(0.1, 0.4, 0.02, -0.3, 0.68, -0.43, -0.25));
  K.put(dark, bx(1.2, 0.1, 0.3, 0, 0.62, 0.6, 0.25), bx(1.2, 0.03, 1.4, 0, 0.6, -0.3), bx(0.16, 0.14, 0.9, 0, 0.62, -0.2));
  K.put(neon, bx(0.26, 0.05, 0.02, 0.3, 0.69, 0.48, 0.5));
  K.put(carbon, at(new THREE.TorusGeometry(0.11, 0.016, 4, 8).rotateX(-0.45), 0.3, 0.75, 0.34));
  // --- 엔진 덮개 + 뒤 창 덮개(루버) 6줄 + 등 위 공기통
  add(facet(loft([R(-1.0, 0.68, 0.7, 0.99, 7), R(-1.7, 0.72, 0.72, 0.91, 7), R(-2.34, 0.76, 0.7, 0.83, 7)], 12)), paint, 0, 0, 0);
  for (let i = 0; i < 6; i++) K.put(dark, bx(1.08, 0.025, 0.13, 0, 1.0 - i * 0.027, -1.12 - i * 0.2, 0.45));
  for (let i = 0; i < 6; i++) K.put(trim, bx(0.02, 0.028, 0.13, 0, 1.002 - i * 0.027, -1.12 - i * 0.2, 0.45));

  for (const s of [-1, 1]) {
    // 문 아래 검은 띠 + 색 줄, 치마 날
    K.put(accent, bx(0.03, 0.12, 2.0, s * 0.962, 0.27, 0.0));
    K.put(trim, bx(0.02, 0.022, 2.0, s * 0.972, 0.345, 0.0));
    K.put(carbon, bx(0.18, 0.022, 1.9, s * 0.98, 0.185, 0.0));
    // 옆으로 흐르는 검은 쐐기 무늬 (문 → 뒤 흡입구) + 가는 색 줄
    K.put(accent, sidePlate([[1.0, 0.46], [-0.5, 0.52], [-0.5, 0.68], [0.2, 0.6]], 0.012, s * 0.962));
    K.put(trim, bx(0.014, 0.016, 1.52, s * 0.966, 0.475, 0.26, 0.04));
    // 뒤 펜더 앞 흡입구: 검은 입 + 가로 살 5줄 (스트레이크)
    K.put(dark, bx(0.34, 0.36, 0.05, s * 0.83, 0.52, -0.5, 0, s * 0.25));
    for (let i = 0; i < 5; i++) K.put(paint, bx(0.36, 0.022, 0.5, s * 0.84, 0.39 + i * 0.065, -0.36, 0, s * 0.22));
    // 문 선 + 손잡이 + 백미러 (각진 판)
    K.put(dark, bx(0.012, 0.36, 0.012, s * 0.96, 0.5, 1.02, 0.2), bx(0.012, 0.3, 0.012, s * 0.965, 0.52, -0.28));
    K.put(metal, bx(0.014, 0.022, 0.13, s * 0.968, 0.6, -0.1));
    K.put(carbon, bx(0.2, 0.02, 0.03, s * 0.76, 0.8, 0.62, 0, 0, s * -0.35));
    K.put(paint, facet(loft([R(0.68, 0.1, 0.8, 0.9, 8, s * 0.87), R(0.56, 0.07, 0.81, 0.88, 8, s * 0.87)], 8)));
    K.put(neon, bx(0.14, 0.012, 0.012, s * 0.87, 0.85, 0.686));
    // 보닛: 접힌 선 + 세모 공기구멍 + 통풍 틈
    K.put(accent, bx(0.03, 0.016, 1.5, s * 0.42, 0.487, 1.6, 0.135));
    K.put(dark, sidePlate([[2.0, 0], [1.5, 0.11], [1.5, -0.11]], 0.012, 0).rotateZ(Math.PI / 2).rotateX(0.135).translate(s * 0.2, 0.712, 0));
    for (let i = 0; i < 3; i++) K.put(dark, bx(0.24, 0.012, 0.045, s * 0.72, 0.742 - i * 0.012, 1.62 - i * 0.11));
    // 앞: 펜더 코의 접이식 눈꺼풀 라이트 + 호박색 방향등
    K.put(dark, bx(0.3, 0.02, 0.26, s * 0.74, 0.5, 2.13, 0.55));
    K.put(lamp, bx(0.11, 0.035, 0.08, s * 0.68, 0.512, 2.15, 0.55), bx(0.11, 0.035, 0.08, s * 0.81, 0.512, 2.15, 0.55));
    K.put(neon, bx(0.3, 0.018, 0.03, s * 0.74, 0.585, 2.01, 0.55), bx(0.1, 0.03, 0.03, s * 0.86, 0.3, 2.42));
    // 앞 모서리 카나드
    K.put(carbon, bx(0.18, 0.014, 0.28, s * 0.99, 0.36, 2.05, 0.3, 0, s * 0.3));
    // 뒤: 육각 후미등 3칸 (테두리 검정)
    for (let k = 0; k < 3; k++) {
      K.put(tailMat, at(new THREE.CylinderGeometry(0.075, 0.075, 0.04, 6).rotateX(Math.PI / 2), s * (0.36 + k * 0.2), 0.66, -2.39));
      K.put(dark, at(new THREE.CylinderGeometry(0.03, 0.03, 0.05, 6).rotateX(Math.PI / 2), s * (0.36 + k * 0.2), 0.66, -2.395));
    }
    K.put(tailMat, bx(0.03, 0.14, 0.03, s * 0.9, 0.4, -2.41));
    // 뒤 펜더 위 통풍 틈
    for (let i = 0; i < 3; i++) K.put(dark, bx(0.26, 0.012, 0.05, s * 0.78, 0.925, -1.2 - i * 0.13));
  }
  doorNumber(add, M, 0.972, 0.52, 0.42, 0.3);
  // --- 앞: 코끝을 가로지르는 LED 줄 (칸칸이) + 아래 검은 그릴 + 살
  K.put(dark, bx(1.3, 0.05, 0.04, 0, 0.3, 2.7), bx(1.24, 0.08, 0.04, 0, 0.225, 2.7));
  for (let i = 0; i < 9; i++) K.put(lamp, bx(0.11, 0.028, 0.03, (i - 4) * 0.14, 0.3, 2.715));
  for (let i = 0; i < 7; i++) K.put(carbon, bx(0.012, 0.08, 0.03, (i - 3) * 0.17, 0.225, 2.712));
  K.put(trim, bx(0.03, 0.05, 0.1, 0.4, 0.2, 2.76));
  // --- 뒤: 검은 판 + 번호판 자리 + 디퓨저 핀 + 네모 배기구 4개
  K.put(dark, bx(1.72, 0.22, 0.03, 0, 0.64, -2.375), bx(1.5, 0.16, 0.03, 0, 0.42, -2.39));
  K.put(accent, bx(0.36, 0.1, 0.02, 0, 0.5, -2.41));
  K.put(neon, bx(1.72, 0.012, 0.035, 0, 0.76, -2.378));
  K.put(carbon, bx(1.6, 0.03, 0.4, 0, 0.27, -2.26, 0.32));
  for (const x of [-0.66, -0.44, -0.22, 0, 0.22, 0.44, 0.66]) K.put(carbon, sidePlate([[-2.0, 0.14], [-2.5, 0.14], [-2.5, 0.34], [-2.1, 0.2]], 0.02, x));
  for (const x of [-0.5, -0.3, 0.3, 0.5]) {
    K.put(metal, bx(0.15, 0.09, 0.2, x, 0.4, -2.36));
    K.put(dark, bx(0.11, 0.055, 0.02, x, 0.4, -2.465));
  }
  K.flush();

  // --- 앞 립 (스플리터 + 끝판)
  const fWing = new THREE.Group();
  body.add(fWing);
  const KF = kit(add, fWing);
  KF.put(carbon, bx(1.84, 0.025, 0.36, 0, 0.165, 2.6));
  KF.put(trim, bx(1.84, 0.02, 0.02, 0, 0.166, 2.785));
  for (const s of [-1, 1]) KF.put(carbon, sidePlate([[2.78, 0.15], [2.42, 0.15], [2.42, 0.27], [2.7, 0.2]], 0.025, s * 0.92));
  KF.flush();
  // --- 높은 뒷날개 (각진 기둥 2개 + 큰 판 + 꺾인 끝판)
  const spoiler = new THREE.Group();
  body.add(spoiler);
  const KS = kit(add, spoiler);
  for (const s of [-1, 1]) {
    KS.put(carbon, sidePlate([[-1.9, 0.82], [-2.3, 0.82], [-2.36, 1.2], [-2.12, 1.2]], 0.05, s * 0.62));
    KS.put(metal, bx(0.014, 0.4, 0.014, s * 0.62, 1.0, -2.3, 0.25));
    KS.put(accent, sidePlate([[-1.94, 1.28], [-2.46, 1.38], [-2.48, 1.06], [-2.02, 1.12]], 0.035, s * 0.95));
    KS.put(trim, bx(0.04, 0.018, 0.5, s * 0.95, 1.335, -2.2, 0.19));
  }
  KS.put(paint, bx(1.88, 0.045, 0.42, 0, 1.22, -2.2, 0.08));
  KS.put(carbon, bx(1.88, 0.012, 0.03, 0, 1.228, -1.99, 0.08));
  KS.flush();
  const drs = add(merge([bx(1.86, 0.03, 0.15), bx(1.86, 0.03, 0.012, 0, 0.025, -0.07)]), trim, 0, 1.27, -2.41, spoiler);
  drs.rotation.x = 0.3;
  const helmet = makeHelmet(add, body, M);
  helmet.position.set(0.3, 0.82, -0.3);
  return {
    helmet, fWing, spoiler, drs,
    A: {
      wheels: W,
      tuck: { f: [0.8, 0.52], r: [0.84, 0.6] },
      helmet: [0.3, 0.82, -0.3],
      visor: [0.98, -0.75],
      armor: { y: 0.74, x: 0.92 },
      ram: { y: 0.12, z: 1.8 },
      spines: [[-0.4, 1.12], [-0.85, 1.08], [-1.3, 0.98], [-1.75, 0.9]],
      booster: { x: 0.9, y0: 0.5, y1: 0.86, z0: -0.6, dz: -1.25 },
      lift: { y: 0.84, z: -2.2, h: 0.36 },
      stab: [0.95, 1.22, -2.2],
      tailFin: [0, 1.08, -0.7],
      wing: [0.95, 0.56, 0.0],
      nitro: { x: 0.2, y: 0.4, z: -2.3, dz: -0.45 },
      vents: [[0.5, 0.6, 0.9], [0.5, 0.56, 1.2], [0.5, 0.52, 1.5]],
      glow: { y: 0.5, z: 1.6, len: 1.4, rot: 0.135, w: 0.05 },
      flames: [[-0.4, 0.4, 0.5, -2.5], [0.4, 0.4, 0.5, -2.5]],
      motor: [0.4, 0.34, -2.4],
      spark: [0.92, 0.25, -1.9],
      seams: [0.97, 0.22, 0.0],
      lean: 0.05,
      drsRest: 0.3,
    },
  };
}
